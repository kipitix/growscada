-- The roles of the server get schemas of their own (ADR 0011), each with its
-- own migration chain: engineering (the Draft: WidgetTypes, Scenes, Widgets,
-- Tag definitions) and runtime (Tag states with the copy of the Tag
-- definitions they need). This chain stays the server's, public: the
-- organizations, the projects, the outbox and the policy jobs, which both
-- roles reference; neither role queries the other's schema.
--
-- This migration moves the existing tables once and marks the baseline of the
-- two new chains: their goose tables are created here, in goose's format,
-- holding this version, so their chains start after it. The data stays.
CREATE SCHEMA engineering;
CREATE SCHEMA runtime;

-- Indexes, constraints, triggers and the pk_id sequences move with their
-- tables; the trigger function update_updated_at_column stays in public.
ALTER TABLE widget_types SET SCHEMA engineering;
ALTER TABLE scenes SET SCHEMA engineering;
ALTER TABLE widgets SET SCHEMA engineering;
ALTER TABLE tags SET SCHEMA engineering;

-- A Tag's state (value, Quality) goes to the Runtime node, with a copy of
-- its definition (name, TagType, Version): a write checks the value against
-- the TagType without asking the Engineering node. Every write takes the
-- next number of one sequence, seq, by which a reader tells the newer of two
-- states of one Tag; the states moved here are numbered in the order the
-- Tags were created.
CREATE SEQUENCE runtime.tag_state_seq;
CREATE TABLE runtime.tags (
    pk_id      SERIAL PRIMARY KEY,
    id         UUID        NOT NULL UNIQUE,
    project_id UUID        NOT NULL,
    name       TEXT        NOT NULL,
    type       VARCHAR(50) NOT NULL,
    version    INTEGER     NOT NULL,
    value      TEXT        NOT NULL,
    quality    VARCHAR(50) NOT NULL,
    seq        BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT fk_runtime_tags_project_id FOREIGN KEY (project_id) REFERENCES projects(id),
    CONSTRAINT chk_runtime_tags_type CHECK (type IN ('string', 'boolean', 'integer')),
    CONSTRAINT chk_runtime_tags_quality CHECK (quality IN ('bad', 'uncertain', 'good'))
);
CREATE INDEX idx_runtime_tags_project_id ON runtime.tags(project_id);
INSERT INTO runtime.tags (id, project_id, name, type, version, value, quality, seq)
    SELECT id, project_id, name, type, version, value, quality, nextval('runtime.tag_state_seq')
    FROM engineering.tags ORDER BY pk_id;

-- What stays in the Draft is the Tag definition.
DROP INDEX engineering.idx_tags_quality;
ALTER TABLE engineering.tags
    DROP COLUMN value,
    DROP COLUMN quality;

-- tag_updated no longer goes through the outbox: the Runtime node publishes
-- it itself, at-most-once, and a client that misses one resyncs.
DELETE FROM outbox WHERE type = 'tag_updated';

CREATE TABLE engineering.goose_db_version (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    version_id bigint NOT NULL,
    is_applied boolean NOT NULL,
    tstamp timestamp NOT NULL DEFAULT now()
);
INSERT INTO engineering.goose_db_version (version_id, is_applied) VALUES (0, true), (20261026000000, true);
CREATE TABLE runtime.goose_db_version (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    version_id bigint NOT NULL,
    is_applied boolean NOT NULL,
    tstamp timestamp NOT NULL DEFAULT now()
);
INSERT INTO runtime.goose_db_version (version_id, is_applied) VALUES (0, true), (20261026000000, true);
