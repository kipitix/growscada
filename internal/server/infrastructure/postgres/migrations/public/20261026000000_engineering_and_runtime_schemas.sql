-- +goose Down
-- +goose StatementBegin
-- Goes back only from the baseline of the two chains: roll them back to it
-- first. A Tag with no state in runtime gets its TagType's zero value with
-- Quality bad, as the Runtime node shows it.
ALTER TABLE engineering.tags
    ADD COLUMN value TEXT,
    ADD COLUMN quality VARCHAR(50);
UPDATE engineering.tags t
    SET value = s.value, quality = s.quality
    FROM runtime.tags s WHERE s.id = t.id;
UPDATE engineering.tags
    SET value = CASE type WHEN 'boolean' THEN 'false' WHEN 'integer' THEN '0' ELSE '' END,
        quality = 'bad'
    WHERE value IS NULL;
ALTER TABLE engineering.tags
    ALTER COLUMN value SET NOT NULL,
    ALTER COLUMN quality SET NOT NULL,
    ADD CONSTRAINT chk_tags_quality CHECK (quality IN ('bad', 'uncertain', 'good'));
CREATE INDEX idx_tags_quality ON engineering.tags(quality);

DROP SCHEMA runtime CASCADE;

ALTER TABLE engineering.tags SET SCHEMA public;
ALTER TABLE engineering.widgets SET SCHEMA public;
ALTER TABLE engineering.scenes SET SCHEMA public;
ALTER TABLE engineering.widget_types SET SCHEMA public;
DROP SCHEMA engineering CASCADE;
